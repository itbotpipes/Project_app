"use client";

import { useState } from "react";
import {
  CheckCircle2,
  Clock,
  PauseCircle,
  FileCheck,
  ArrowRight,
  Copy,
  Check,
  TrendingUp,
  Layers,
  Sparkles,
  Info,
  Star,
} from "lucide-react";
import { cn } from "@/lib/cn";
import { Card, Badge } from "../_components/ui";
import TaskLink from "../_components/TaskLink";
import type { EmployeeDailyWorkSummary, DailySummaryTaskItem } from "@/lib/dailyWorkSummaryTypes";

export default function DailySummaryTemplateCard({
  summary,
}: {
  summary: EmployeeDailyWorkSummary;
}) {
  const [copied, setCopied] = useState(false);

  function handleCopyText() {
    // Generate clean bullet-point text matching the official format
    const lines: string[] = [];
    lines.push(`### Daily Work Summary – ${summary.dateLabel}`);
    lines.push("");
    lines.push(`**Employee:** ${summary.employeeName}`);
    lines.push(`**Role:** ${summary.roleTitle} (${summary.departmentName})`);
    lines.push("");
    lines.push(`**Task Overview**`);
    lines.push(`- Total Tasks: ${summary.totalTasks}`);
    lines.push(`- Completed: ${summary.completedCount}`);
    lines.push(`- Pending: ${summary.pendingCount}`);
    lines.push(`- On Hold: ${summary.onHoldCount}`);
    lines.push(`- In Review: ${summary.inReviewCount}`);
    lines.push(`- Carry Forward: ${summary.carryForwardCount}`);
    lines.push("");

    lines.push(`**Completed Today**`);
    if (summary.completedTasks.length === 0) {
      lines.push(`- (No tasks completed today)`);
    } else {
      summary.completedTasks.forEach((t) => {
        lines.push(`- ${t.title}`);
      });
    }
    lines.push("");

    lines.push(`**Pending Tasks**`);
    if (summary.pendingTasks.length === 0) {
      lines.push(`- (No pending tasks)`);
    } else {
      summary.pendingTasks.forEach((t) => {
        lines.push(`- ${t.title}`);
      });
    }
    lines.push("");

    if (summary.onHoldTasks.length > 0) {
      lines.push(`**On Hold**`);
      summary.onHoldTasks.forEach((t) => {
        const reason = t.holdReason ? ` (Reason: ${t.holdReason})` : "";
        lines.push(`- ${t.title}${reason}`);
      });
      lines.push("");
    }

    if (summary.inReviewTasks.length > 0) {
      lines.push(`**In Review**`);
      summary.inReviewTasks.forEach((t) => {
        lines.push(`- ${t.title}`);
      });
      lines.push("");
    }

    lines.push(`**Tomorrow's Carry Forward**`);
    if (summary.tomorrowCarryForwardTasks.length === 0) {
      lines.push(`- (No tasks to carry forward)`);
    } else {
      summary.tomorrowCarryForwardTasks.forEach((t) => {
        lines.push(`- ${t.title}`);
      });
    }
    lines.push("");

    lines.push(`**Daily Productivity: ${summary.productivityLabel}**`);

    const textToCopy = lines.join("\n");
    navigator.clipboard.writeText(textToCopy).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    });
  }

  // Productivity visual tone
  const pct = summary.productivityPercentage;
  const prodTone =
    pct === null
      ? "bg-slate-100 text-slate-700 border-slate-300"
      : pct >= 80
      ? "bg-emerald-50 text-emerald-800 border-emerald-300"
      : pct >= 50
      ? "bg-blue-50 text-blue-800 border-blue-300"
      : "bg-amber-50 text-amber-800 border-amber-300";

  const progressBg =
    pct === null
      ? "bg-slate-300"
      : pct >= 80
      ? "bg-emerald-500"
      : pct >= 50
      ? "bg-blue-600"
      : "bg-amber-500";

  return (
    <Card className="p-6 md:p-8 space-y-7 border border-slate-200/90 shadow-sm bg-white rounded-2xl">
      {/* Header bar */}
      <div className="flex flex-wrap items-start justify-between gap-4 pb-5 border-b border-slate-100">
        <div>
          <div className="flex items-center gap-2">
            <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-blue-50 text-blue-700 border border-blue-200">
              <Sparkles size={13} className="text-blue-600" /> Official Work Report
            </span>
            {summary.isAutoGenerated && (
              <span className="inline-flex items-center px-2 py-0.5 rounded-full text-[11px] font-medium bg-emerald-50 text-emerald-700 border border-emerald-200">
                Auto-Generated
              </span>
            )}
          </div>
          <h2 className="text-xl md:text-2xl font-bold text-slate-900 mt-2">
            Daily Work Summary – {summary.dateLabel}
          </h2>
          <p className="text-sm text-slate-600 mt-0.5">
            <span className="font-semibold text-slate-900">Employee:</span> {summary.employeeName} ·{" "}
            <span className="text-slate-500">{summary.roleTitle} ({summary.departmentName})</span>
          </p>
        </div>

        {/* Copy button */}
        <button
          onClick={handleCopyText}
          className={cn(
            "flex items-center gap-2 px-3.5 py-2 rounded-xl text-xs font-medium border transition-all shadow-xs",
            copied
              ? "bg-emerald-50 border-emerald-300 text-emerald-700"
              : "bg-white border-slate-200 text-slate-700 hover:bg-slate-50 hover:border-slate-300 active:scale-95"
          )}
        >
          {copied ? <Check size={14} className="text-emerald-600" /> : <Copy size={14} className="text-slate-500" />}
          {copied ? "Copied to Clipboard!" : "Copy Summary Text"}
        </button>
      </div>

      {/* Task Overview Grid */}
      <div>
        <h3 className="text-xs font-bold text-slate-400 tracking-wider uppercase mb-3">
          Task Overview
        </h3>
        <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-6 gap-3">
          <div className="p-3.5 rounded-xl bg-slate-50/80 border border-slate-200/80">
            <div className="text-xs text-slate-500 font-medium">Total Tasks</div>
            <div className="text-2xl font-bold text-slate-900 mt-0.5">{summary.totalTasks}</div>
          </div>
          <div className="p-3.5 rounded-xl bg-emerald-50/60 border border-emerald-200/80">
            <div className="text-xs text-emerald-700 font-medium flex items-center gap-1">
              <CheckCircle2 size={13} /> Completed
            </div>
            <div className="text-2xl font-bold text-emerald-700 mt-0.5">{summary.completedCount}</div>
          </div>
          <div className="p-3.5 rounded-xl bg-sky-50/60 border border-sky-200/80">
            <div className="text-xs text-sky-700 font-medium flex items-center gap-1">
              <Clock size={13} /> Pending
            </div>
            <div className="text-2xl font-bold text-sky-700 mt-0.5">{summary.pendingCount}</div>
          </div>
          <div className="p-3.5 rounded-xl bg-amber-50/60 border border-amber-200/80">
            <div className="text-xs text-amber-700 font-medium flex items-center gap-1">
              <PauseCircle size={13} /> On Hold
            </div>
            <div className="text-2xl font-bold text-amber-700 mt-0.5">{summary.onHoldCount}</div>
          </div>
          <div className="p-3.5 rounded-xl bg-violet-50/60 border border-violet-200/80">
            <div className="text-xs text-violet-700 font-medium flex items-center gap-1">
              <FileCheck size={13} /> In Review
            </div>
            <div className="text-2xl font-bold text-violet-700 mt-0.5">{summary.inReviewCount}</div>
          </div>
          <div className="p-3.5 rounded-xl bg-orange-50/60 border border-orange-200/80">
            <div className="text-xs text-orange-700 font-medium flex items-center gap-1">
              <ArrowRight size={13} /> Carry Forward
            </div>
            <div className="text-2xl font-bold text-orange-700 mt-0.5">{summary.carryForwardCount}</div>
          </div>
        </div>
      </div>

      {/* Prominent Daily Productivity Banner */}
      <div className={cn("p-5 rounded-2xl border flex flex-col md:flex-row items-center justify-between gap-5", prodTone)}>
        <div className="space-y-1.5 w-full md:w-auto">
          <div className="flex items-center gap-2">
            <TrendingUp size={18} />
            <span className="text-xs font-bold uppercase tracking-wider">
              Task Completion Productivity
            </span>
          </div>
          <p className="text-xs opacity-80 max-w-xl">
            Calculated as: <span className="font-semibold">(Completed Tasks ÷ Total Tasks Planned for the Day) × 100</span>.
            {pct === null && " (No tasks planned or worked on this day)."}
          </p>
        </div>

        <div className="flex items-center gap-4 w-full md:w-auto justify-end">
          <div className="w-36 hidden sm:block">
            <div className="h-3 w-full bg-slate-200/80 rounded-full overflow-hidden">
              <div
                className={cn("h-full transition-all duration-700 rounded-full", progressBg)}
                style={{ width: `${pct !== null ? Math.min(100, Math.max(5, pct)) : 0}%` }}
              />
            </div>
          </div>
          <div className="text-3xl md:text-4xl font-extrabold tracking-tight">
            {summary.productivityLabel}
          </div>
        </div>
      </div>

      {/* Quality Reward Points Banner (Requirement 7) */}
      {(summary.totalApprovedPointsEarned ?? 0) > 0 && (
        <div className="p-4 rounded-2xl border border-purple-200/90 bg-gradient-to-r from-purple-50/70 via-white to-purple-50/40 flex flex-wrap items-center justify-between gap-4 shadow-2xs">
          <div className="flex items-center gap-3">
            <div className="grid h-10 w-10 place-items-center rounded-xl bg-purple-600 text-white shadow-xs">
              <Star size={20} />
            </div>
            <div>
              <div className="text-xs font-bold uppercase tracking-wider text-purple-950 flex items-center gap-1.5">
                Quality Reward Points Earned
                <span className="text-[10px] font-normal text-purple-700 bg-purple-100 px-2 py-0.5 rounded-full">
                  Separate from completion %
                </span>
              </div>
              <div className="text-xs text-slate-600 mt-0.5">
                Base Points: <strong className="text-slate-800">{summary.basePointsEarned ?? 0} pts</strong> (Size × Priority) + Manager Bonus: <strong className="text-purple-700">+{summary.qualityBonusPointsEarned ?? 0} pts</strong>
              </div>
            </div>
          </div>

          <div className="text-right">
            <div className="text-2xl font-black text-purple-900">
              {summary.totalApprovedPointsEarned} <span className="text-xs font-semibold text-purple-600">pts</span>
            </div>
            <div className="text-[10px] text-slate-400 font-medium">Official Approved Points</div>
          </div>
        </div>
      )}

      {/* Work Summary Sections */}
      <div className="space-y-6 pt-2">
        {/* Completed Today */}
        <div className="rounded-xl border border-emerald-100 bg-emerald-50/20 p-4 md:p-5">
          <div className="flex items-center justify-between mb-3">
            <h4 className="text-sm font-bold text-emerald-900 flex items-center gap-2">
              <CheckCircle2 size={16} className="text-emerald-600" />
              Completed Today ({summary.completedTasks.length})
            </h4>
          </div>
          {summary.completedTasks.length === 0 ? (
            <p className="text-xs text-slate-400 italic py-1 pl-6">No tasks were marked closed today.</p>
          ) : (
            <ul className="space-y-2">
              {summary.completedTasks.map((t) => (
                <li key={t.id} className="flex items-start gap-2.5 text-sm text-slate-800">
                  <span className="text-emerald-500 font-bold mt-0.5">•</span>
                  <div className="flex-1 flex flex-wrap items-center justify-between gap-2">
                    <TaskLink taskId={t.id} className="font-medium hover:underline text-slate-900">
                      {t.title}
                    </TaskLink>
                    <div className="flex items-center gap-1.5 text-xs">
                      {t.totalApprovedPoints != null && (
                        <span className="px-2 py-0.5 rounded-md bg-purple-100 text-purple-800 text-[11px] font-semibold flex items-center gap-1">
                          <Star size={11} className="text-purple-600" />
                          {t.totalApprovedPoints} pts
                        </span>
                      )}
                      {t.kpiName && (
                        <span className="px-2 py-0.5 rounded-md bg-slate-100 text-slate-600 text-[11px]">
                          {t.kpiName}
                        </span>
                      )}
                      <span className="px-2 py-0.5 rounded-md bg-emerald-100 text-emerald-800 text-[11px] font-medium">
                        Closed
                      </span>
                    </div>
                  </div>
                </li>
              ))}
            </ul>
          )}
        </div>

        {/* Pending Tasks */}
        <div className="rounded-xl border border-sky-100 bg-sky-50/20 p-4 md:p-5">
          <div className="flex items-center justify-between mb-3">
            <h4 className="text-sm font-bold text-sky-900 flex items-center gap-2">
              <Clock size={16} className="text-sky-600" />
              Pending Tasks ({summary.pendingTasks.length})
            </h4>
          </div>
          {summary.pendingTasks.length === 0 ? (
            <p className="text-xs text-slate-400 italic py-1 pl-6">No pending tasks remaining.</p>
          ) : (
            <ul className="space-y-2">
              {summary.pendingTasks.map((t) => (
                <li key={t.id} className="flex items-start gap-2.5 text-sm text-slate-800">
                  <span className="text-sky-500 font-bold mt-0.5">•</span>
                  <div className="flex-1 flex flex-wrap items-center justify-between gap-2">
                    <TaskLink taskId={t.id} className="font-medium hover:underline text-slate-900">
                      {t.title}
                    </TaskLink>
                    <div className="flex items-center gap-1.5 text-xs">
                      {t.carryCount && t.carryCount > 0 ? (
                        <span className="px-2 py-0.5 rounded-md bg-orange-100 text-orange-800 text-[11px] font-medium">
                          Carried {t.carryCount}d
                        </span>
                      ) : null}
                      <span className="px-2 py-0.5 rounded-md bg-sky-100 text-sky-800 text-[11px] font-medium capitalize">
                        {t.status.replace("_", " ").toLowerCase()}
                      </span>
                    </div>
                  </div>
                </li>
              ))}
            </ul>
          )}
        </div>

        {/* In Review */}
        {summary.inReviewTasks.length > 0 && (
          <div className="rounded-xl border border-violet-100 bg-violet-50/20 p-4 md:p-5">
            <h4 className="text-sm font-bold text-violet-900 flex items-center gap-2 mb-3">
              <FileCheck size={16} className="text-violet-600" />
              In Review ({summary.inReviewTasks.length})
            </h4>
            <ul className="space-y-2">
              {summary.inReviewTasks.map((t) => (
                <li key={t.id} className="flex items-start gap-2.5 text-sm text-slate-800">
                  <span className="text-violet-500 font-bold mt-0.5">•</span>
                  <div className="flex-1 flex flex-wrap items-center justify-between gap-2">
                    <TaskLink taskId={t.id} className="font-medium hover:underline text-slate-900">
                      {t.title}
                    </TaskLink>
                    <span className="px-2 py-0.5 rounded-md bg-violet-100 text-violet-800 text-[11px] font-medium">
                      Pending Review
                    </span>
                  </div>
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* On Hold */}
        {summary.onHoldTasks.length > 0 && (
          <div className="rounded-xl border border-amber-100 bg-amber-50/20 p-4 md:p-5">
            <h4 className="text-sm font-bold text-amber-900 flex items-center gap-2 mb-3">
              <PauseCircle size={16} className="text-amber-600" />
              On Hold ({summary.onHoldTasks.length})
            </h4>
            <ul className="space-y-2">
              {summary.onHoldTasks.map((t) => (
                <li key={t.id} className="flex items-start gap-2.5 text-sm text-slate-800">
                  <span className="text-amber-500 font-bold mt-0.5">•</span>
                  <div className="flex-1 flex flex-wrap items-center justify-between gap-2">
                    <div>
                      <TaskLink taskId={t.id} className="font-medium hover:underline text-slate-900">
                        {t.title}
                      </TaskLink>
                      {t.holdReason && (
                        <p className="text-xs text-amber-800 mt-0.5">
                          <span className="font-medium">Reason:</span> {t.holdReason}
                        </p>
                      )}
                    </div>
                    <span className="px-2 py-0.5 rounded-md bg-amber-100 text-amber-800 text-[11px] font-medium">
                      On Hold
                    </span>
                  </div>
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* Tomorrow's Carry Forward */}
        <div className="rounded-xl border border-orange-200/90 bg-orange-50/25 p-4 md:p-5">
          <div className="flex items-center justify-between mb-3">
            <h4 className="text-sm font-bold text-orange-950 flex items-center gap-2">
              <ArrowRight size={16} className="text-orange-600" />
              Tomorrow&apos;s Carry Forward ({summary.tomorrowCarryForwardTasks.length})
            </h4>
            {summary.carriedForwardToDate && (
              <span className="text-xs text-slate-500">
                To: <span className="font-medium text-slate-700">{summary.carriedForwardToDate}</span>
              </span>
            )}
          </div>
          {summary.tomorrowCarryForwardTasks.length === 0 ? (
            <p className="text-xs text-slate-400 italic py-1 pl-6">
              All tasks completed! Nothing carried forward to the next working day.
            </p>
          ) : (
            <ul className="space-y-2">
              {summary.tomorrowCarryForwardTasks.map((t) => (
                <li key={t.id} className="flex items-start gap-2.5 text-sm text-slate-800">
                  <span className="text-orange-500 font-bold mt-0.5">•</span>
                  <div className="flex-1 flex flex-wrap items-center justify-between gap-2">
                    <TaskLink taskId={t.id} className="font-medium hover:underline text-slate-900">
                      {t.title}
                    </TaskLink>
                    <div className="flex items-center gap-1.5 text-xs">
                      {t.carryCount && t.carryCount > 0 ? (
                        <span className="px-2 py-0.5 rounded-md bg-orange-100 text-orange-800 text-[11px] font-medium">
                          Carried {t.carryCount}d
                        </span>
                      ) : null}
                      <span className="px-2 py-0.5 rounded-md bg-slate-100 text-slate-700 text-[11px] font-medium capitalize">
                        {t.status.replace("_", " ").toLowerCase()}
                      </span>
                    </div>
                  </div>
                </li>
              ))}
            </ul>
          )}
        </div>
      </div>
    </Card>
  );
}
