/** Normalizes a date into YYYY-MM-DD string */
export function formatDateKey(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

/** Formats a date into "23 November 2026" format matching the template requirement */
export function formatDisplayDate(d: Date): string {
  const months = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
  ];
  return `${d.getDate()} ${months[d.getMonth()]} ${d.getFullYear()}`;
}

/**
 * Formats a clean, executive-ready department daily work summary for sharing
 * via WhatsApp, Slack, Email, or printing.
 */
export function generateDepartmentSummaryShareText(dept: DepartmentDailyWorkSummary): string {
  const lines: string[] = [];
  lines.push(`🏢 *Department Daily Work Summary – ${dept.departmentName}*`);
  lines.push(`📅 *Date:* ${dept.dateLabel}`);
  lines.push("");
  lines.push(`📊 *Department Task Overview*`);
  lines.push(`• Total Team Members: ${dept.totalEmployees}`);
  lines.push(`• Total Planned Tasks: ${dept.totalTasks}`);
  lines.push(`• Completed: ${dept.completedCount}`);
  lines.push(`• Pending: ${dept.pendingCount}`);
  lines.push(`• On Hold: ${dept.onHoldCount}`);
  lines.push(`• In Review: ${dept.inReviewCount}`);
  lines.push(`• Tomorrow's Carry Forward: ${dept.carryForwardCount}`);
  lines.push(`• Department Productivity: *${dept.productivityLabel}*`);
  lines.push("");

  lines.push(`━━━━━━━━━━━━━━━━━━━━━━━━━`);
  lines.push(`✅ *Completed Today (${dept.completedCount})*`);
  if (dept.completedTasks.length === 0) {
    lines.push(`• (No tasks completed today)`);
  } else {
    dept.completedTasks.forEach((t) => {
      lines.push(`• ${t.title} – ${t.assigneeName}`);
    });
  }
  lines.push("");

  lines.push(`⏳ *Pending Tasks (${dept.pendingCount})*`);
  if (dept.pendingTasks.length === 0) {
    lines.push(`• (No pending tasks)`);
  } else {
    dept.pendingTasks.forEach((t) => {
      lines.push(`• ${t.title} – ${t.assigneeName}`);
    });
  }
  lines.push("");

  if (dept.onHoldTasks.length > 0) {
    lines.push(`⏸️ *On Hold (${dept.onHoldCount})*`);
    dept.onHoldTasks.forEach((t) => {
      const reason = t.holdReason ? ` (Reason: ${t.holdReason})` : "";
      lines.push(`• ${t.title} – ${t.assigneeName}${reason}`);
    });
    lines.push("");
  }

  if (dept.inReviewTasks.length > 0) {
    lines.push(`🔍 *In Review (${dept.inReviewCount})*`);
    dept.inReviewTasks.forEach((t) => {
      lines.push(`• ${t.title} – ${t.assigneeName}`);
    });
    lines.push("");
  }

  lines.push(`➡️ *Tomorrow's Carry Forward (${dept.carryForwardCount})*`);
  if (dept.tomorrowCarryForwardTasks.length === 0) {
    lines.push(`• (No tasks to carry forward)`);
  } else {
    dept.tomorrowCarryForwardTasks.forEach((t) => {
      lines.push(`• ${t.title} – ${t.assigneeName}`);
    });
  }
  lines.push("");

  lines.push(`━━━━━━━━━━━━━━━━━━━━━━━━━`);
  lines.push(`👥 *Team Member Breakdown:*`);
  dept.members.forEach((m, idx) => {
    lines.push(
      `${idx + 1}. *${m.employeeName}* (${m.roleTitle}): ${m.completedCount}/${m.totalTasks} completed (${m.productivityLabel})`
    );
  });
  lines.push("");
  lines.push(`_Generated via TaskFlow Northern Star_`);

  return lines.join("\n");
}
